import { existsSync } from "node:fs";
import { readFileSync, writeFileSync, ensureDirSync } from "@visulima/fs";
import { resolve, join, dirname, relative } from "@visulima/path";
import chalk from "@visulima/colorize";
import { pail } from "@visulima/pail";
import { extractDrizzleTables, type DrizzleTableInfo } from "../utils/drizzle-tables.js";
import type { ApiGenRootConfig, AppLayout } from "../types/api-gen.json.js";

// ---------------------------------------------------------------------------
// 类型
// ---------------------------------------------------------------------------

/**
 * 生成层级
 *
 * - `entity`:实体层 —— `packages/shared-types/src/zschema/<domain>.zschema.ts`
 *   只放**全字段**的实体 schema(Entity / Insert / Query),**不放 HTTP 契约**。
 * - `model`:HTTP 契约层 —— `<app>/src/modules/<domain>/<domain>.model.ts`
 *   放裁剪后的 body / query / params / response(带信封)。
 */
export type ZschemaLayer = "entity" | "model" | "both";

export interface GenerateZschemaOptions {
  /** 指定单个 domain(对应 dbschema 表名去掉 Table 后缀的 kebab 名) */
  domain?: string;
  /** 只给指定 app 生成 model.ts(缺省 = 所有带 modules 的 app) */
  app?: string;
  /** 生成哪一层:entity(实体层) / model(HTTP 契约层) / both(缺省) */
  layer?: ZschemaLayer;
  /** 覆盖已有文件(marker 存在时) */
  force?: boolean;
  /** 允许给"还没有 controller 的 domain"创建模块目录并生成 model.ts */
  create?: boolean;
}

// ---------------------------------------------------------------------------
// 常量
// ---------------------------------------------------------------------------

const CWD = process.cwd();
const CONFIG_PATH = resolve(CWD, ".vscode/api-gen.json");
const MARKER = "// Auto-generated by api-gen gen-zschema — do not edit manually.";

/**
 * 服务端生成 / 内部维护的字段 —— 创建/更新体里不给客户端。
 *
 * 只做**交集**:表里没有的列不写进 omit 集合(zod 的 `.omit()` 遇到不存在的 key
 * 会直接抛错,模块加载即崩)。
 *
 * ⚠️ 状态机字段(status / closedAt / paidAt)与内部字段(isPublic / ownerId /
 * rawSnapshot)**不在这里** —— 那些要逐域评估,不能批量套用。
 */
const SERVER_FIELD_CANDIDATES = [
  "createdAt",
  "createdBy",
  "deletedAt",
  "deletedBy",
  "id",
  "organizationId",
  "siteId",
  "tenantId",
  "updatedAt",
  "updatedBy",
];

// ---------------------------------------------------------------------------
// 路径工具
// ---------------------------------------------------------------------------

/** 计算相对 import 路径(保证以 ./ 或 ../ 开头,正斜杠) */
function relImport(fromDir: string, toDir: string): string {
  const p = relative(fromDir, toDir).replace(/\\/g, "/");
  if (!p) return ".";
  return p.startsWith(".") ? p : `./${p}`;
}

/** 相对路径指向某个文件(不含扩展名) */
function relImportFile(fromDir: string, toFile: string): string {
  const p = relative(fromDir, dirname(toFile)).replace(/\\/g, "/");
  const base = p.startsWith(".") ? p : `./${p}`;
  return `${base}/${toFile.split("/").pop()?.replace(/\.ts$/, "") ?? ""}`;
}

/**
 * 解析"raw 的 import 说明符"
 *
 * 优先级:包说明符(探测到的 `@workspace/database/zschema`)
 *   → raw 目录的桶(有 index.ts 就导桶)
 *   → 具体某个 raw 文件
 */
function resolveRawImport(
  fromDir: string,
  packageImport: string | null,
  rawDirAbs: string,
  rawFileAbs: string,
): string {
  if (packageImport) return packageImport;
  if (existsSync(join(rawDirAbs, "index.ts"))) return relImport(fromDir, rawDirAbs);
  return relImportFile(fromDir, rawFileAbs);
}

/** 解析"utils 的 import 说明符"(信封 / QueryShape / InferDTO) */
function resolveUtilsImport(
  fromDir: string,
  packageImport: string | null,
  utilsDirAbs: string,
): string {
  if (packageImport) return packageImport;
  return relImport(fromDir, utilsDirAbs);
}

// ---------------------------------------------------------------------------
// 模板:实体层(shared-types)
// ---------------------------------------------------------------------------

function generateEntityContent(
  table: DrizzleTableInfo,
  rawImport: string,
  utilsImport: string,
): string {
  const P = table.pascalName;
  return [
    "/** biome-ignore-all lint/style/useNamingConvention: 契约文件固定约束 */",
    MARKER,
    "",
    `import { ${P}RawInsert, ${P}RawSelect } from "${rawImport}";`,
    `import { z } from "zod";`,
    `import type { InferDTO } from "${utilsImport}";`,
    "",
    "/**",
    " * 实体层:表全字段,**不做 HTTP 裁剪**。",
    " *",
    " * HTTP 契约(body / query / params / response)在各 app 的",
    " * `<domain>.model.ts` 里裁剪 —— 本文件只描述\"表的形状\"。",
    " */",
    `const ${P}Entity = z.object({ ...${P}RawSelect.shape });`,
    "",
    `export const ${P}ZSchema = {`,
    `  /** 实体(前后端共享) */`,
    `  Entity: ${P}Entity,`,
    `  /** 插入形状(给各 app 的 model.ts 裁剪用) */`,
    `  Insert: ${P}RawInsert,`,
    `  /** 查询形状(给各 app 的 model.ts 裁剪用) */`,
    `  Query: z.object({ ...${P}RawInsert.partial().shape }),`,
    `} as const;`,
    "",
    `export type ${P}Contract = InferDTO<typeof ${P}ZSchema>;`,
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// 模板:HTTP 契约层(app 的 model.ts)
// ---------------------------------------------------------------------------

/** 计算要 omit 的服务端字段(与表列取交集) */
function pickServerFields(table: DrizzleTableInfo): string[] {
  const cols = new Set(table.columns);
  return SERVER_FIELD_CANDIDATES.filter((c) => cols.has(c)).sort();
}

function generateModelContent(
  table: DrizzleTableInfo,
  rawImport: string,
  utilsImport: string,
): string {
  const P = table.pascalName;
  const serverFields = pickServerFields(table);

  const omitBlock =
    serverFields.length > 0
      ? serverFields.map((f) => `    ${f}: true,`).join("\n")
      : "    // 表里没有识别到服务端字段 —— 按业务补齐后再收紧";

  return [
    "/**",
    ` * ${P} 的 HTTP 契约层。`,
    " *",
    " * 从 raw 派生 —— 分两层:",
    " * - 实体层(`" + rawImport + "`):表全字段",
    " * - 契约层(本文件):排除服务端字段,得到\"这个接口收什么、返回什么\"",
    " *",
    " * ⚠️ 状态机字段(status / closedAt)与内部字段(isPublic / ownerId / rawSnapshot)",
    " * **没有自动排除** —— 它们要逐域评估,确认业务语义后再补进 SERVER_FIELDS。",
    " */",
    "",
    `import { ${P}RawInsert, ${P}RawSelect } from "${rawImport}";`,
    "import {",
    "  type InferDTO,",
    "  PageResultSchema,",
    "  QueryShape,",
    "  ResultSchema,",
    `} from "${utilsImport}";`,
    `import { z } from "zod";`,
    "",
    "/** 实体:表全字段(响应裁剪后只暴露接口真正返回的列) */",
    `const ${P}Entity = z.object({ ...${P}RawSelect.shape });`,
    "",
    "/** 服务端生成 / 内部维护的字段 —— 创建/更新时不给客户端 */",
    "const SERVER_FIELDS = {",
    omitBlock,
    "} as const;",
    "",
    `export const ${P}Model = {`,
    "  /** 创建请求体:白名单(排除服务端字段) */",
    "  Create: z.object({",
    `    ...${P}RawInsert.omit(SERVER_FIELDS).shape,`,
    "  }),",
    "  /** 路径参数 */",
    '  IdParam: z.object({ id: z.string() }),',
    "  /** 列表查询:全字段可筛(数字/布尔已 coerce)+ 搜索 */",
    "  ListQuery: z.object({",
    `    ...QueryShape(${P}RawInsert.partial().shape),`,
    "    search: z.string().optional(),",
    "  }),",
    "  /** 列表响应:PageResult<" + P + "> 信封 */",
    `  ListResponse: PageResultSchema(${P}Entity),`,
    "  /** 单条响应:Result<" + P + "> 信封 */",
    `  Response: ResultSchema(${P}Entity),`,
    "  /** 更新请求体:同 Create 字段集,全可选 */",
    "  Update: z",
    "    .object({",
    `      ...${P}RawInsert.omit(SERVER_FIELDS).shape,`,
    "    })",
    "    .partial(),",
    "} as const;",
    "",
    `export type ${P}ModelContract = InferDTO<typeof ${P}Model>;`,
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// 保护机制
// ---------------------------------------------------------------------------

function hasMarker(content: string): boolean {
  return content.split("\n").some((l) => l.startsWith(MARKER));
}

/**
 * 写文件(带保护机制)
 * @returns "written" | "skipped-manual" | "skipped-exists"
 */
function writeGuarded(
  outPath: string,
  content: string,
  force: boolean,
): "written" | "skipped-manual" | "skipped-exists" {
  if (existsSync(outPath)) {
    const existing = readFileSync(outPath);
    if (!hasMarker(existing)) {
      pail.warn(`跳过(手动维护): ${chalk.dim(outPath)}`);
      return "skipped-manual";
    }
    if (!force) {
      pail.debug(`已存在骨架,跳过: ${chalk.dim(outPath)}`);
      return "skipped-exists";
    }
  }
  ensureDirSync(dirname(outPath));
  writeFileSync(outPath, content);
  return "written";
}

// ---------------------------------------------------------------------------
// 主入口
// ---------------------------------------------------------------------------

export async function generateZschemaCommand(opts: GenerateZschemaOptions = {}): Promise<void> {
  if (!existsSync(CONFIG_PATH)) {
    console.error(chalk.red("缺少配置文件 .vscode/api-gen.json，请先执行 api-gen info"));
    process.exit(1);
  }

  const raw = readFileSync(CONFIG_PATH);
  const config = JSON.parse(raw) as ApiGenRootConfig;

  if (!config.common) {
    pail.warn("未检测到公共合约层(common),没有 dbschema 可扫描");
    return;
  }

  const { zschemaRoot, zschemaRawDir, dbschemaFiles } = config.common;
  if (!zschemaRoot) {
    pail.warn("未配置 common.zschemaRoot,请先执行 api-gen info");
    return;
  }
  if (!zschemaRawDir) {
    pail.warn("未配置 common.zschemaRawDir,请先执行 api-gen info");
    return;
  }
  if (!dbschemaFiles.length) {
    pail.warn("未配置 dbschemaFiles(应在 packages/database/src/drizzle/*.dbschema.ts)");
    return;
  }

  const layer: ZschemaLayer = opts.layer ?? "both";
  const wantEntity = layer === "entity" || layer === "both";
  const wantModel = layer === "model" || layer === "both";

  const zschemaRootAbs = resolve(CWD, zschemaRoot);
  const rawDirAbs = resolve(CWD, zschemaRawDir);
  // utils 目录:实体层/契约层都要用(信封 + QueryShape + InferDTO)
  const utilsDirAbs = resolve(zschemaRootAbs, "..", "utils");

  // 实体层的 import 说明符
  const entityRawImport = resolveRawImport(
    zschemaRootAbs,
    config.common.rawImportPath,
    rawDirAbs,
    join(rawDirAbs, "index.ts"),
  );
  const entityUtilsImport = resolveUtilsImport(
    zschemaRootAbs,
    config.common.sharedTypesUtilsImport,
    utilsDirAbs,
  );

  // app 列表(要生成 model.ts 的目标)
  const modelApps: AppLayout[] = config.apps.filter(
    (a) => a.modulesDir && (!opts.app || a.appName === opts.app),
  );
  if (wantModel && opts.app && modelApps.length === 0) {
    pail.warn(`未找到 app "${opts.app}"(需要它带 modules 目录)`);
  }

  let totalTables = 0;
  let totalFiles = 0;
  let skipped = 0;

  for (const schemaFile of dbschemaFiles) {
    const schemaAbs = resolve(CWD, schemaFile);
    if (!existsSync(schemaAbs)) {
      pail.warn(`dbschema 文件不存在,跳过: ${chalk.dim(schemaFile)}`);
      continue;
    }

    const tables = extractDrizzleTables(schemaAbs);
    if (!tables.length) continue;

    for (const table of tables) {
      if (opts.domain && table.fileName !== opts.domain) continue;

      // raw 是前置依赖(raw 里才有 RawInsert / RawSelect)
      const rawFile = join(rawDirAbs, `${table.fileName}.dbschema.raw.ts`);
      if (!existsSync(rawFile)) {
        pail.warn(
          `缺少 raw 文件: ${chalk.dim(rawFile)},请先运行 \`api-gen raw\``,
        );
        continue;
      }

      // ---- 实体层:shared-types/<domain>.zschema.ts ----
      if (wantEntity) {
        const outPath = join(zschemaRootAbs, `${table.fileName}.zschema.ts`);
        const result = writeGuarded(
          outPath,
          generateEntityContent(table, entityRawImport, entityUtilsImport),
          Boolean(opts.force),
        );
        if (result === "written") {
          totalFiles++;
          console.log(chalk.dim(`  + ${table.fileName}.zschema.ts  (实体层 · ${table.pascalName})`));
        } else {
          skipped++;
        }
      }

      // ---- 契约层:<app>/modules/<domain>/<domain>.model.ts ----
      if (wantModel) {
        for (const app of modelApps) {
          const moduleDir = join(resolve(CWD, app.modulesDir!), table.fileName);
          const controllerFile = join(moduleDir, `${table.fileName}.controller.ts`);
          const modelFile = join(moduleDir, `${table.fileName}.model.ts`);

          // 只给"已经是模块"(有 controller)的 domain 生成 model.ts;
          // --create 才允许凭空建模块目录
          if (!existsSync(controllerFile) && !opts.create) {
            continue;
          }

          const appRawImport = resolveRawImport(
            moduleDir,
            config.common.rawImportPath,
            rawDirAbs,
            rawFile,
          );
          const appUtilsImport = resolveUtilsImport(
            moduleDir,
            config.common.sharedTypesUtilsImport,
            utilsDirAbs,
          );

          const result = writeGuarded(
            modelFile,
            generateModelContent(table, appRawImport, appUtilsImport),
            Boolean(opts.force),
          );
          if (result === "written") {
            totalFiles++;
            console.log(
              chalk.dim(
                `  + ${app.appName}/${table.fileName}/${table.fileName}.model.ts  (HTTP 契约层 · ${table.pascalName})`,
              ),
            );
          } else {
            skipped++;
          }
        }
      }

      totalTables++;
    }
  }

  if (totalFiles === 0 && skipped === 0) {
    pail.warn("未在任何 dbschema 文件中找到 pgTable 导出");
    return;
  }

  const summary = opts.force
    ? `已强制覆盖 ${totalFiles} 个契约文件(共 ${totalTables} 张表)`
    : `生成了 ${totalFiles} 个契约文件,跳过 ${skipped} 个(共 ${totalTables} 张表)`;
  pail.success(summary);
  console.log(
    chalk.dim(
      "提示:实体层只放全字段;HTTP 契约在 app 的 model.ts 里裁剪 —— 响应记得 .pick(),别把内部列泄给前端",
    ),
  );
}

export default async function generateZschema(opts?: GenerateZschemaOptions): Promise<void> {
  await generateZschemaCommand(opts);
}
