function genSubModuleIndex(
  files: { name: string; exports: NamedExport[] }[] = [],
  subModules: SubModuleInfo[] = [],
): string {
  const lines: string[] = [];
  lines.push(MARKER);
  lines.push("");

  // 按文件名排序保证确定性
  const sortedFiles = [...files].sort((a, b) => a.name.localeCompare(b.name));
  const sortedSubs = [...subModules].sort((a, b) => a.dirName.localeCompare(b.dirName));

  for (const f of sortedFiles) {
    const values = f.exports.filter((e) => e.kind === "value").map((e) => e.name);
    const types = f.exports.filter((e) => e.kind === "type").map((e) => e.name);

    if (values.length > 0) {
      lines.push(`export { ${values.join(", ")} } from "./${f.name}";`);
    }
    if (types.length > 0) {
      lines.push(`export type { ${types.join(", ")} } from "./${f.name}";`);
    }
  }

  // 子目录 barrel re-export(递归级联)
  for (const m of sortedSubs) {
    const values = m.valueExports;
    const types = m.typeExports;
    if (values.length > 0) {
      lines.push(`export { ${values.join(", ")} } from "./${m.dirName}";`);
    }
    if (types.length > 0) {
      lines.push(`export type { ${types.join(", ")} } from "./${m.dirName}";`);
    }
  }

  lines.push("");

  return lines.join("\n");
}

function genGroupIndex(
  modules: SubModuleInfo[],
  mode: ExportMode = "full"
): string {
  const lines: string[] = [];
  lines.push(MARKER);
  lines.push("");

  const sorted = [...modules].sort((a, b) => a.dirName.localeCompare(b.dirName));

  const filterByMode = (
    names: string[],
    tags: Map<string, ReadonlySet<string>>,
    kind: "value" | "type"
  ): string[] => {
    if (mode === "full") return names;
    return names.filter((n) =>
      shouldExport({ name: n, kind, tags: tags.get(n) ?? new Set() }, mode)
    );
  };

  for (const m of sorted) {
    const values = filterByMode(m.valueExports, m.valueTags, "value");
    const types = filterByMode(m.typeExports, m.typeTags, "type");
    if (values.length > 0) {
      lines.push(`export { ${values.join(", ")} } from "./${m.dirName}";`);
    }
    if (types.length > 0) {
      lines.push(`export type { ${types.join(", ")} } from "./${m.dirName}";`);
    }
  }

  lines.push("");

  return lines.join("\n");
}

