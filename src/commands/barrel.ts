function hasAutoGenMarker(filePath: string): boolean {
  if (!existsSync(filePath)) return false;
  const content = readFileSync(filePath, { encoding: "utf-8" });
  return content.startsWith(MARKER);
}

/** 对比新旧内容，无变化 + 有标记则不写入 */
function shouldWrite(filePath: string, newContent: string): boolean {
  if (!existsSync(filePath)) return true;
  const old = readFileSync(filePath, { encoding: "utf-8" });
  return old !== newContent;
}

