export interface BarrelOptions {
  group?: string;
  dryRun?: boolean;
  /** 库导出模式:仅导出 @public 符号,排除 @internal 与未标注符号 */
  lib?: boolean;
}

export async function barrelCommand(options: BarrelOptions = {}): Promise<void> {
  const configPath = resolve(process.cwd(), ".vscode/api-config.json");
  if (!existsSync(configPath)) {
    console.error(chalk.red("缺少配置文件 .vscode/api-config.json，请先执行 api-gen init"));
    process.exit(1);
  }

  const raw = readFileSync(configPath, { encoding: "utf-8" });
  const config = JSON.parse(raw) as ApiConfig;

  const ei = config.exportIndex;
  if (!ei || !ei.includes?.length) {
    pail.warn(
      "未配置 barrel 导出组。请在 .vscode/api-config.json 中添加 exportIndex，如：\n" +
      chalk.dim(JSON.stringify({ exportIndex: { includes: ["utils"], utils: ["packages/contract/src/utils"] } }, null, 2)),
    );
    return;
  }

  let groupNames = ei.includes;
  if (options.group) {
    if (!groupNames.includes(options.group)) {
      pail.error(`未找到导出组 "${options.group}"。可用组：${groupNames.join(", ")}`);
      return;
    }
    groupNames = [options.group];
  }

  console.log(chalk.bold("\n🔷 api-gen barrel — 桶导出生成"));
  if (options.dryRun) {
    console.log(chalk.yellow("  --dry-run 模式，仅预览不写入\n"));
  }
  if (options.lib) {
    console.log(chalk.yellow("  --lib 模式，仅导出 @public 标记的符号(@internal / 未标注均不导出)\n"));
  }

  const mode: ExportMode = options.lib ? "lib" : "full";

  let totalPaths = 0;
  for (const name of groupNames) {
    const rawPaths = ei[name];
    if (rawPaths == null) {
      // 数组缺失视为空数组,后面统一走"空数组"分支
    }
    const safeRaw = rawPaths ?? [];

    // 拆分包含项与排除项：以 "!" 开头的视为排除
    const excluded: string[] = [];
    const explicitIncluded: string[] = [];
    for (const p of safeRaw) {
      if (p.startsWith("!")) excluded.push(p);
      else explicitIncluded.push(p);
    }
    for (const p of excluded) {
      pail.info(`已排除（配置忽略）：${chalk.dim(p.slice(1))}`);
    }

    if (isPathLike(name)) {
      // 路径形式组：included 是组名下的子内容列表（子目录 + 散文件），
      // 一次性处理整组，汇总到组级 index.ts。
      let included = explicitIncluded;
      if (included.length === 0) {
        // 空数组 → 自动递归展开(无需先跑 sync)。
        // 排除模式去掉 `!` 前缀,共享扫描函数按路径/前缀/basename 匹配。
        const excludePatterns = excluded.map((p) => p.slice(1));
        const groupAbs = resolve(process.cwd(), name);
        if (!existsSync(groupAbs)) {
          pail.warn(`目录不存在，跳过：${chalk.dim(name)}`);
          continue;
        }
        const auto = scanPathGroupChildren(groupAbs, name, { exclude: excludePatterns });
        if (auto.length === 0) {
          pail.warn(`"${name}" 目录下无内容，跳过组`);
          continue;
        }
        included = auto;
        console.log(chalk.green(`  ✓ ${name}: 自动展开 ${auto.length} 个子项`));
        for (const p of auto) {
          console.log(chalk.dim(`    - ${p}`));
        }
      }
      processPathGroup(name, included, !!options.dryRun, excluded, mode);
      totalPaths += included.length;
    } else {
      // 约定名组:空数组依然要警告(约定名组没有"组名路径"可扫)
      if (explicitIncluded.length === 0) {
        pail.warn(`"${name}" 未配置路径，跳过。请编辑 exportIndex.${name} 添加路径`);
        continue;
      }
      for (const rootDir of explicitIncluded) {
        processGroup(name, rootDir, !!options.dryRun, excluded, mode);
        totalPaths++;
      }
    }
  }

  const statusMode = options.dryRun ? "(dry-run)" : "已生成";
  pail.success(`\n  ${statusMode} ${totalPaths} 个路径的 barrel 导出`);
  console.log(chalk.dim("提示：所有生成文件均带有自动标记，可随时安全地重新运行 `api-gen barrel` 覆盖"));
}

export default async function barrel(options?: BarrelOptions): Promise<void> {
  await barrelCommand(options);
}
