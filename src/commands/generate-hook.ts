// ---------------------------------------------------------------------------
// server.ts edenPrefix 自动探测
// ---------------------------------------------------------------------------

/**
 * 从 b2b-api `server.ts` 里探测 eden 链前缀,返回 `api.v1` 这样的点分字符串。
 *
 * 匹配规则(基于 Elysia 调用链):
 *   1. `new Elysia({ prefix: "/api" })`      → 顶层 prefix
 *   2. `.group("/v1", ...)`                  → 顶层 .group(...)
 *   3. 拼起来 `api.v1` → eden.api.v1.<domain>...
 *
 * 启发式:只能找到第一个 `new Elysia` 的 prefix 和第一个顶层 `.group(...)`。
 * 复杂链(嵌套 group / 重挂载)请手配 `.vscode/api-gen.json` 的 edenPrefix 字段。
 */
function detectEdenPrefixFromServer(appRoot: string | undefined): string | null {
  if (!appRoot) return null;
  const serverPath = resolve(CWD, appRoot, "src/server.ts");
  if (!existsSync(serverPath)) return null;

  const src = readFileSync(serverPath);
  const parts: string[] = [];

  // 1) new Elysia({ prefix: "/api" })
  const prefixMatch = src.match(/new\s+Elysia\s*\(\s*\{[^}]*prefix\s*:\s*["'`](\/[^"'`]+)["'`]/);
  if (prefixMatch) {
    parts.push(prefixMatch[1].replace(/^\//, "").replace(/\/$/, ""));
  }

  // 2) 顶层 .group("/v1", ...) — 匹配第一个顶层调用(不在其它 group 里)
  const groupMatch = src.match(/^\s*\.group\(\s*["'`](\/[^"'`]+)["'`]/m);
  if (groupMatch) {
    parts.push(groupMatch[1].replace(/^\//, "").replace(/\/$/, ""));
  }

  return parts.length > 0 ? parts.join(".") : null;
}

// ---------------------------------------------------------------------------
// 类型
// ---------------------------------------------------------------------------

export interface GenerateHookOptions {
  domain?: string;
  /** "web" | "b2b-admin"; 缺省 = 同时写两个目标 */
  target?: "web" | "b2b-admin";
}

interface HookEntry {
  /** hook 函数名,如 useCurrentSite */
  fnName: string;
  /** 路由方法 */
  method: RouteSpec["method"];
  /** 路由路径(用于注释) */
  routePath: string;
  /** eden 链(不含尾部方法名),如 "api.v1.site" / "api.v1.site({ id })" */
  chain: string;
  /** 尾部方法名(get/post/put/patch/delete) */
  tail: string;
  /** 路径里的 :param 名(顺序) */
  paramNames: string[];
  /** 路由是否声明了 query */
  hasQuery: boolean;
  /** 路由是否声明了 body */
  hasBody: boolean;
  /** Eden 类型键(用于推导 query / body 类型) */
  typeKey: string;
  /** 类型别名前缀,如 "ListSite" → ListSiteQuery / ListSiteBody */
  aliasPrefix: string;
}

const CWD = process.cwd();
const CONFIG_PATH = resolve(CWD, ".vscode/api-gen.json");
const CLI_CONFIG_PATH = resolve(CWD, ".vscode/api-config.json");
const MARKER = "// Auto-generated by api-gen gen-hook — do not edit manually.";

// ---------------------------------------------------------------------------
// 命名规则
// ---------------------------------------------------------------------------

/** kebab-case → PascalCase;同时把 `/` 当段分隔(用于 "batch/delete" → "BatchDelete") */
function kebabToPascal(name: string): string {
  return name
    .split(/[-_/]/)
    .map((s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : ""))
    .join("");
}

/** 去掉路径里的所有 `:param` 段(用于 hook 名 / 子路径后缀) */
function stripPathParams(path: string): string {
  return path
    .split("/")
    .filter((s) => !s.startsWith(":"))
    .join("/");
}

/**
 * 从 controller 路径 + 路由方法推导 hook 函数名
 *
 * 规则(与 tradeflow eden-hooks.md 习惯一致):
 * - .get("/")              → useList<Domain>
 * - .get("/current")       → useCurrent<Domain>
 * - .get("/:id")           → use<Domain>Detail
 * - .post("/")             → useCreate<Domain>
 * - .put("/:id")           → useUpdate<Domain>
 * - .patch("/:id/toggle")  → useUpdate<Domain>Toggle    (带子路径避免重名)
 * - .delete("/:id")        → useDelete<Domain>
 * - .delete("/batch")      → useDelete<Domain>Batch     (带子路径避免重名)
 * - .post("/:id/x")        → useCreate<Domain>X          (带子路径避免重名)
 *
 * 子路径后缀规则:去掉所有 `:param` 段后,剩下非空路径拼到动词后(PascalCase),
 * 这样 PUT /:id 和 PATCH /:id/toggle / DELETE /batch 不会撞同名。
 */
function deriveHookName(route: RouteSpec, domainPascal: string): string {
  const cleanedPath = route.path.replace(/^\//, "");
  // 静态子路径(去掉 :param 后剩的),拼到动词后避免同名冲突
  const staticPath = stripPathParams(cleanedPath);
  const staticPascal = staticPath ? kebabToPascal(staticPath) : "";

  if (route.method === "POST") {
    return `useCreate${domainPascal}${staticPascal}`;
  }
  if (route.method === "DELETE") {
    return `useDelete${domainPascal}${staticPascal}`;
  }
  if (route.method === "PUT" || route.method === "PATCH") {
    return `useUpdate${domainPascal}${staticPascal}`;
  }

  // GET
  if (staticPath === "") {
    // cleanedPath 完全是 :param(无静态段)→ use<Domain>Detail
    if (cleanedPath.includes(":")) return `use${domainPascal}Detail`;
    // cleanedPath === "current" → useCurrent
    if (cleanedPath === "current") return `useCurrent${domainPascal}`;
    // cleanedPath 空 → useList
    return `useList${domainPascal}`;
  }
  if (staticPath === "current") return `useCurrent${domainPascal}`;
  return `use${domainPascal}${staticPascal}`;
}

// ---------------------------------------------------------------------------
// eden 链拼装
// ---------------------------------------------------------------------------

/** 属性访问片段:含 `-` 的段必须用 bracket access */
function accessSeg(seg: string): string {
  return seg.includes("-") ? `["${seg}"]` : seg;
}

/**
 * 拼 eden 链
 *
 *   eden.api.v1.site.get
 *   eden.api.v1.site({ id }).get
 *   eden.api.v1.site({ id }).toggle.patch
 *   eden.api.v1["site-product"].batch.delete
 *
 * 注意:路径参数段渲染成 `({ name })` **直接跟在上一段后面**(不加点),
 * `eden.site.({ id })` 是非法语法。
 */
function buildEdenChain(
  prefixSegments: string[],
  domain: string,
  routePath: string,
): { chain: string; paramNames: string[] } {
  let chain = prefixSegments.join(".");
  if (chain) chain += ".";
  chain += accessSeg(domain);

  const paramNames: string[] = [];
  const segs = routePath.replace(/^\//, "").split("/").filter(Boolean);
  for (const seg of segs) {
    if (seg.startsWith(":")) {
      const name = seg.slice(1);
      paramNames.push(name);
      chain += `({ ${name} })`;
    } else {
      chain += `.${accessSeg(seg)}`;
    }
  }
  return { chain, paramNames };
}

/** Eden 类型键:`Eden["api"]["v1"]["site"]["get"]` */
function buildTypeKey(prefixSegments: string[], domain: string, method: string): string {
  const segs = [...prefixSegments, domain, method.toLowerCase()];
  return `Eden${segs.map((s) => `["${s}"]`).join("")}`;
}

// ---------------------------------------------------------------------------
// 渲染
// ---------------------------------------------------------------------------

/** hook 函数参数签名(路径参数部分) */
function buildParamSig(entry: HookEntry): string {
  if (entry.paramNames.length === 0) return "";
  if (entry.paramNames.length === 1) return `${entry.paramNames[0]}: string`;
  const inner = entry.paramNames.map((n) => `${n}: string`).join("; ");
  return `{ ${entry.paramNames.join(", ")} }: { ${inner} }`;
}

/** invalidate 用到的"根列表"queryKey */
function buildRootGetKey(domainChain: string): string {
  return `eden.${domainChain}.get.queryKey()`;
}

/**
 * 渲染单个 hook 函数
 *
 * 规则(与 tradeflow eden-hooks.md 对齐):
 * - GET  → useApiQuery(eden.<chain>.<method>.queryOptions(query, { enabled, staleTime }))
 * - 写操作 + 有 body → useApiMutation(eden.<chain>.<method>.mutationOptions(), { onSuccess })
 * - 写操作 + 无 body + 有路径参数 → 走 raw eden client(options proxy 的 delete/patch 只能拿到工厂)
 * - 写操作 + 无 body + 无路径参数 → useApiMutation(eden.<chain>.<method>.mutationOptions(), ...)
 *
 * query 参数**平铺**传(不包 `{ query: ... }`),类型从 Eden 推导。
 */
function renderHook(
  entry: HookEntry,
  opts: {
    hookConfig: Required<HookConfig>;
    domainChain: string;
    hasRootGet: boolean;
  },
): string {
  const { hookConfig, domainChain, hasRootGet } = opts;
  const sig = buildParamSig(entry);
  const staleTime = hookConfig.staleTime;
  const rootGetKey = hasRootGet ? buildRootGetKey(domainChain) : "";

  if (entry.method === "GET") {
    const isDetail = entry.paramNames.length > 0;
    // 查询类型别名只在"根列表"路由上生成(Eden 的类型键按 method 唯一,详情路由会撞键)
    const withQueryType = entry.hasQuery && entry.paramNames.length === 0;
    const fnParams = [
      sig,
      withQueryType ? `params?: ${entry.aliasPrefix}Query` : "",
      isDetail ? "enabled = !!id" : "enabled = true",
    ]
      .filter(Boolean)
      .join(", ");

    const queryArg = withQueryType ? "params ?? {}" : "{}";
    const queryTypeAlias = withQueryType
      ? [
          `/** GET ${entry.routePath} 的查询参数(Eden 推导) */`,
          `export type ${entry.aliasPrefix}Query = NonNullable<`,
          `  ${entry.typeKey}["~types"]["input"]`,
          ">;",
        ]
      : [];

    return [
      ...queryTypeAlias,
      `/** GET ${entry.routePath}${isDetail ? " —— 详情" : " —— 列表"} */`,
      `export function ${entry.fnName}(${fnParams}) {`,
      "  const eden = useEden();",
      "  return useApiQuery(",
      `    eden.${entry.chain}.${entry.tail}.queryOptions(`,
      `      ${queryArg},`,
      `      { enabled, staleTime: ${staleTime} }`,
      "    )",
      "  );",
      "}",
    ].join("\n");
  }

  // ---- 写操作 ----
  const bodyTypeAlias = entry.hasBody
    ? [
        `/** ${entry.method} ${entry.routePath} 的请求体(Eden 推导) */`,
        `export type ${entry.aliasPrefix}Body = NonNullable<`,
        `  ${entry.typeKey}["~types"]["input"]`,
        ">;",
      ]
    : [];

  const invalidateBlock = rootGetKey
    ? [
        "        queryClient.invalidateQueries({",
        `          queryKey: ${rootGetKey},`,
        "        });",
      ]
    : [];

  // 无 body + 有路径参数 → 走 raw eden client(delete/patch 的 options proxy 只能拿到工厂)
  if (!entry.hasBody && entry.paramNames.length > 0) {
    const mutateSig =
      entry.paramNames.length === 1
        ? `${entry.paramNames[0]}: string`
        : `{ ${entry.paramNames.join(", ")} }: { ${entry.paramNames.map((n) => `${n}: string`).join("; ")} }`;
    return [
      ...bodyTypeAlias,
      `/** ${entry.method} ${entry.routePath} —— 路径参数在 mutate 时传入 */`,
      `export function ${entry.fnName}() {`,
      "  const eden = useEden();",
      "  const edenClient = useEdenClient();",
      "  const queryClient = useQueryClient();",
      "  return useApiMutation(",
      "    {",
      `      mutationFn: async (${mutateSig}) => {`,
      `        const { data, error } = await edenClient.${entry.chain}.${entry.tail}();`,
      "        if (error) {",
      "          throw error;",
      "        }",
      "        return data;",
      "      },",
      "    },",
      "    {",
      "      onSuccess: () => {",
      ...invalidateBlock,
      "      },",
      "    }",
      "  );",
      "}",
    ].join("\n");
  }

  // 有 body(或无 body 无参数)→ mutationOptions
  const fnParamsList = sig ? `${sig}, ` : "";
  return [
    ...bodyTypeAlias,
    `/** ${entry.method} ${entry.routePath} —— body 在 mutate 时传入 */`,
    `export function ${entry.fnName}(${fnParamsList}) {`,
    "  const eden = useEden();",
    "  const queryClient = useQueryClient();",
    "  return useApiMutation(",
    `    eden.${entry.chain}.${entry.tail}.mutationOptions(),`,
    "    {",
    "      onSuccess: () => {",
    ...invalidateBlock,
    "      },",
    "    }",
    "  );",
    "}",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// 文件生成
// ---------------------------------------------------------------------------

function generateHookFile(
  entries: HookEntry[],
  hookConfig: Required<HookConfig>,
  domainChain: string,
  hasRootGet: boolean,
): string {
  const lines: string[] = [];
  lines.push(MARKER);
  lines.push("");

  const needEden = entries.some(
    (e) => e.hasBody || (e.hasQuery && e.method === "GET" && e.paramNames.length === 0),
  );
  const needClient = entries.some(
    (e) => e.method !== "GET" && !e.hasBody && e.paramNames.length > 0,
  );

  if (hookConfig.apiHooksImport) {
    lines.push(
      `import { useApiMutation, useApiQuery } from "${hookConfig.apiHooksImport}";`,
    );
    lines.push('import { useQueryClient } from "@tanstack/react-query";');
  } else {
    lines.push(
      'import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";',
    );
  }
  const rpcImports = [
    ...(needEden ? ["type Eden"] : []),
    "useEden",
    ...(needClient ? ["useEdenClient"] : []),
  ];
  lines.push(`import { ${rpcImports.join(", ")} } from "${hookConfig.rpcImport}";`);
  lines.push("");
  lines.push("// 类型全部从 Eden 推导(不手写响应类型、不写类型断言)");
  lines.push("// query 参数平铺传 —— 不要包 { query: ... },那样筛选和分页会全部丢失");
  lines.push("");

  for (const e of entries) {
    lines.push(renderHook(e, { hookConfig, domainChain, hasRootGet }));
    lines.push("");
  }
  return lines.join("\n");
}

function hasMarker(content: string): boolean {
  return content.startsWith(MARKER);
}

// ---------------------------------------------------------------------------
// 配置读取
// ---------------------------------------------------------------------------

/** 读 hook 配置(.vscode/api-config.json 的 hooks 段,缺省用内置默认值) */
function readHookConfig(): Required<HookConfig> {
  if (!existsSync(CLI_CONFIG_PATH)) return { ...DEFAULT_HOOK_CONFIG };
  try {
    const cfg = JSON.parse(readFileSync(CLI_CONFIG_PATH, { encoding: "utf-8" })) as ApiConfig;
    return { ...DEFAULT_HOOK_CONFIG, ...(cfg.hooks ?? {}) };
  } catch {
    return { ...DEFAULT_HOOK_CONFIG };
  }
}

// ---------------------------------------------------------------------------
// 主入口
// ---------------------------------------------------------------------------

export async function generateHookCommand(opts: GenerateHookOptions = {}): Promise<void> {
  if (!existsSync(CONFIG_PATH)) {
    console.error(chalk.red("缺少配置文件 .vscode/api-gen.json，请先执行 api-gen info"));
    process.exit(1);
  }

  const raw = readFileSync(CONFIG_PATH);
  const config = JSON.parse(raw) as ApiGenRootConfig;

  // 找 b2b-api app(hook 源) — 提前到 edenPrefix 探测前用
  const b2bApi = config.apps.find((a) => a.appType === "b2b-api");
  if (!b2bApi || !b2bApi.modulesDir) {
    pail.warn("未找到 b2b-api app(需在 .vscode/api-gen.json 标记 appType=\"b2b-api\")");
    return;
  }

  // Eden 路径前缀:从配置读,缺省自动从 b2b-api server.ts 探测(prefix + 顶层 .group())。
  // 探测失败才退化为 ""(直接挂载)。
  let edenPrefix = config.edenPrefix ?? "";
  if (edenPrefix === "") {
    const detected = detectEdenPrefixFromServer(b2bApi.appRoot);
    if (detected) {
      edenPrefix = detected;
      console.log(chalk.dim(`  探测到 server.ts 路径前缀: eden.${edenPrefix}.*`));
    }
  }
  const prefixSegments = edenPrefix ? edenPrefix.split(".") : [];

  // 找目标 app(web / b2b-admin)
  const targets: AppLayout[] = config.apps.filter(
    (a) => (a.appType === "web" || a.appType === "b2b-admin") && a.appRoot,
  );
  if (opts.target) {
    const t = targets.find((a) => a.appType === opts.target);
    if (!t) {
      pail.warn(`未找到 appType=${opts.target} 的 app`);
      return;
    }
    targets.length = 0;
    targets.push(t);
  }
  if (targets.length === 0) {
    pail.warn("未找到 web / b2b-admin app,无法生成 hook");
    return;
  }

  const modulesDir = resolve(CWD, b2bApi.modulesDir);
  if (!existsSync(modulesDir)) {
    pail.warn(`b2b-api modules 目录不存在: ${chalk.dim(modulesDir)}`);
    return;
  }

  const hookConfig = readHookConfig();
  const controllers = scanAllControllers(modulesDir);
  const filtered = opts.domain
    ? controllers.filter(
        (c) =>
          c.domain === opts.domain ||
          c.name.replace(/Controller$/, "").replace(/^./, (ch) => ch.toLowerCase()) === opts.domain,
      )
    : controllers;

  if (filtered.length === 0) {
    pail.warn("未找到 controller(检查 b2b-api 的 modules 目录)");
    return;
  }

  let totalFiles = 0;

  for (const ctrl of filtered) {
    const domainKebab =
      ctrl.domain ||
      ctrl.name.replace(/Controller$/, "").replace(/^./, (ch) => ch.toLowerCase());
    const domainPascal = kebabToPascal(domainKebab);

    // 该 controller 是否有"根列表"路由(GET /)—— invalidate 依赖它
    const hasRootGet = ctrl.routes.some(
      (r) => r.method === "GET" && stripPathParams(r.path.replace(/^\//, "")) === "",
    );
    const domainChain = `${prefixSegments.join(".")}${prefixSegments.length ? "." : ""}${accessSeg(domainKebab)}`;

    const rawEntries: HookEntry[] = ctrl.routes.map((r) => {
      const { chain, paramNames } = buildEdenChain(prefixSegments, domainKebab, r.path);
      const fnName = deriveHookName(r, domainPascal);
      return {
        fnName,
        method: r.method as HookEntry["method"],
        routePath: r.path,
        chain,
        tail: r.method.toLowerCase(),
        paramNames,
        hasQuery: Boolean(r.schemaRefs?.query),
        hasBody: Boolean(r.schemaRefs?.body),
        typeKey: buildTypeKey(prefixSegments, domainKebab, r.method),
        // 类型别名前缀:去掉 use 前缀 → ListSite / DetailSite / CreateSite
        aliasPrefix: fnName.replace(/^use/, ""),
      };
    });

    // 去重:极少数 controller 有完全相同 method+path 的路由(IDE 偶发);
    // 同 fnName 重复会触发 TS 重复导出,所以这里去重 + warn。
    const seen = new Set<string>();
    const entries: HookEntry[] = [];
    for (const e of rawEntries) {
      if (seen.has(e.fnName)) {
        pail.warn(`  hook "${e.fnName}" 重复定义,跳过(method=${e.method} path=${e.routePath})`);
        continue;
      }
      seen.add(e.fnName);
      entries.push(e);
    }

    const content = generateHookFile(entries, hookConfig, domainChain, hasRootGet);

    for (const target of targets) {
      const hooksDir = resolve(CWD, target.appRoot, "src/hooks/api");
      ensureDirSync(hooksDir);
      const outPath = join(hooksDir, `use-${domainKebab}.ts`);

      // 已存在但无 marker → 手动维护,跳过
      if (existsSync(outPath)) {
        const existing = readFileSync(outPath);
        if (!hasMarker(existing)) {
          pail.warn(`跳过(手动维护): ${chalk.dim(outPath)}`);
          continue;
        }
      }

      writeFileSync(outPath, content);
      totalFiles++;
      console.log(
        chalk.dim(`  + ${target.appName}/src/hooks/api/use-${domainKebab}.ts  (${entries.length} hooks)`),
      );
    }
  }

  if (totalFiles === 0) {
    pail.warn("未生成任何 hook 文件");
    return;
  }

  pail.success(`已生成 ${totalFiles} 个 hook 文件`);
  if (edenPrefix) {
    pail.info(`Eden prefix: ${chalk.cyan(edenPrefix)} (来自 .vscode/api-gen.json)`);
  }
  pail.info(
    `hook 封装: ${chalk.cyan(hookConfig.apiHooksImport || "@tanstack/react-query")} · Eden 类型从 ${chalk.cyan(hookConfig.rpcImport)} 推导`,
  );
}

export default async function generateHook(opts?: GenerateHookOptions): Promise<void> {
  await generateHookCommand(opts);
}
